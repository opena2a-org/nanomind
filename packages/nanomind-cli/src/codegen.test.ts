import { describe, it } from 'node:test';
import assert from 'node:assert';
import { generateArtifact, listArtifactTypes } from './codegen.ts';

// A project name that no template text carries, so finding it in the output
// shows that the templates were rendered with this context.
const PROJECT = 'planted-project-7c41';

const CONTEXT = {
  projectName: PROJECT,
  projectType: 'mcp_server',
  language: 'typescript',
};

// Text no generated template carries: a request to an internal registry
// route, the name of the registry credential, and an action taken from a branch.
const FORBIDDEN = ['/internal/', 'OPENA2A_API_KEY', '@main'];

// Text of a build attestation step: the registry action, the attestation
// route, a CI secret handed to a step, and an authorization header.
const ATTESTATION_STEP = ['opena2a-registry/action', 'build-attestation', 'secrets.', 'Authorization:'];

function renderAll(context: typeof CONTEXT = CONTEXT): Array<[string, string]> {
  return listArtifactTypes().map((type) => [type, generateArtifact(type, context)]);
}

function occurrences(outputs: Array<[string, string]>, texts: string[]): string[] {
  return outputs.flatMap(([type, output]) =>
    texts.filter((text) => output.includes(text)).map((text) => `${type}: ${text}`),
  );
}

describe('generated templates', () => {
  it('call no internal registry route, name no registry credential and take no action from a branch', () => {
    const outputs = renderAll();
    // Positive control: the run rendered the templates with the planted context.
    assert.ok(
      outputs.some(([, output]) => output.includes(PROJECT)),
      'no generated template carries the planted project name',
    );
    assert.deepStrictEqual(occurrences(outputs, FORBIDDEN), []);
  });

  it('carry no build attestation step', () => {
    assert.ok(!(listArtifactTypes() as string[]).includes('build-action'), 'build-action is a listed type');
    assert.deepStrictEqual(occurrences(renderAll(), ATTESTATION_STEP), []);
  });

  it('pin every action they reference by a full commit sha', () => {
    const references = renderAll().flatMap(([type, output]) =>
      [...output.matchAll(/^\s*(?:-\s+)?uses:\s+(\S+)/gm)].map((match) => `${type}: ${match[1]}`),
    );
    // Positive control: the check reads the action references the templates carry.
    assert.ok(references.length > 0, 'no template references an action');
    const unpinned = references.filter((reference) => !/: [\w.-]+\/[\w./-]+@[0-9a-f]{40}$/.test(reference));
    assert.deepStrictEqual(unpinned, []);
  });

  it('name the project on their first line', () => {
    for (const [type, output] of renderAll()) {
      assert.strictEqual(output.split('\n')[0], `# Security scan for ${PROJECT}. Generated by NanoMind.`, type);
    }
  });

  it('keep any project name inside the first-line comment', () => {
    const name = ['name', 'run: planted', 'stage\r#', 'yaml\u0085  ', 'tail\\'].join('\n');
    const plain = new Map(renderAll());
    for (const [type, output] of renderAll({ ...CONTEXT, projectName: name })) {
      const lines = output.split('\n');
      assert.strictEqual(lines.length, plain.get(type)!.split('\n').length, `${type}: ${output}`);
      assert.match(lines[0], /^# Security scan for [\p{L}\p{M}\p{N} ._-]+\. Generated by NanoMind\.$/u, type);
      assert.deepStrictEqual(lines.slice(1), plain.get(type)!.split('\n').slice(1), type);
    }
  });
});
